const dropdown = (categoryCode, key, name, allowedValues, options = {}) => ({
  id: `${categoryCode.toLowerCase()}-${key}`,
  key,
  name,
  fieldType: "dropdown",
  required: options.required ?? true,
  defaultValue: options.defaultValue ?? allowedValues[0],
  allowedValues,
  affectsPricing: options.affectsPricing ?? false,
  pricingModifierType: options.pricingModifierType || "none",
  pricingModifierConfig: options.pricingModifierConfig || {},
  buyerVisible: options.buyerVisible ?? true,
  internalVisible: true,
  appearsOnLotCard: options.appearsOnLotCard ?? true,
  appearsInDescription: options.appearsInDescription ?? true,
  helpText: options.helpText || "",
});

const field = (categoryCode, key, name, fieldType, options = {}) => ({
  id: `${categoryCode.toLowerCase()}-${key}`,
  key,
  name,
  fieldType,
  required: options.required ?? false,
  defaultValue: options.defaultValue ?? (fieldType === "boolean" ? false : ""),
  allowedValues: options.allowedValues || [],
  affectsPricing: options.affectsPricing ?? false,
  pricingModifierType: options.pricingModifierType || "none",
  pricingModifierConfig: options.pricingModifierConfig || {},
  buyerVisible: options.buyerVisible ?? true,
  internalVisible: true,
  appearsOnLotCard: options.appearsOnLotCard ?? false,
  appearsInDescription: options.appearsInDescription ?? false,
  helpText: options.helpText || "",
});

